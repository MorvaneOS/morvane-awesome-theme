#!/usr/bin/env python3
"""Builds the MorvaneOS awesome theme.

    python tools/build.py

Needs only Python. Output goes to theme/; commit it, it's what the package installs.

The theme loads awesome's default theme and changes its colours and wallpaper, so
the rest (icons, sizes) stays awesome's. The MorvaneOS installer points awesome's
rc.lua at it (beautiful.init).
"""

import shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

# Keep in step with the window colours in morvane-gtk-theme
PASTEL = '#F4A6C6'
PAPER = '#F5EEF3'
WHITE = '#FFFFFF'
SURFACE = '#1A1220'
SELECTED = '#4A3552'
BORDER = '#2A1C32'
MUTED = '#A898AC'
URGENT = '#F0506E'
URGENT_BG = '#B3261E'
WALLPAPER = '/usr/share/backgrounds/morvaneos/twilight.png'

THEME = f'''\
-- MorvaneOS theme for awesome: generated by tools/build.py in morvane-awesome-theme,
-- edit that instead. awesome's default theme with the MorvaneOS colours and wallpaper.

local gears = require("gears")
local theme_assets = require("beautiful.theme_assets")
local dpi = require("beautiful.xresources").apply_dpi

local theme = dofile(gears.filesystem.get_themes_dir() .. "default/theme.lua")

theme.bg_normal     = "{SURFACE}"
theme.bg_focus      = "{SELECTED}"
theme.bg_urgent     = "{URGENT_BG}"
theme.bg_minimize   = "{BORDER}"
theme.bg_systray    = theme.bg_normal

theme.fg_normal     = "{MUTED}"
theme.fg_focus      = "{PAPER}"
theme.fg_urgent     = "{WHITE}"
theme.fg_minimize   = "{PAPER}"

-- The focused window has a Pastel Pink border
theme.border_normal = "{BORDER}"
theme.border_focus  = "{PASTEL}"
theme.border_marked = "{URGENT}"

theme.taglist_bg_focus = "{PASTEL}"
theme.taglist_fg_focus = "{SURFACE}"

-- Drawn from the colours when the default theme loads, so redrawn here
local taglist_square_size = dpi(4)
theme.taglist_squares_sel = theme_assets.taglist_squares_sel(taglist_square_size, theme.fg_normal)
theme.taglist_squares_unsel = theme_assets.taglist_squares_unsel(taglist_square_size, theme.fg_normal)
theme.awesome_icon = theme_assets.awesome_icon(theme.menu_height, theme.bg_focus, theme.fg_focus)

theme.wallpaper = "{WALLPAPER}"

return theme
'''


def build() -> None:
	out = ROOT / 'theme'
	shutil.rmtree(out, ignore_errors=True)
	out.mkdir()
	(out / 'theme.lua').write_text(THEME)
	print('Built the awesome theme.')


if __name__ == '__main__':
	build()
